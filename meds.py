def analogs(key, region=None):
    d = CORE[key]
    lines = [f"### 🔁 Чем заменить {d['n'].lower()}",
             "**С тем же действующим веществом** (это одно и то же лекарство, отличаются производитель, цена и вспомогательные вещества):"]
    lines += _brands(d, region)
    group = [k for k, x in CORE.items() if k != key and x["g"] == d["g"] and not x["note"]]
    if group:
        lines += ["", f"**Другие вещества с похожим действием** ({d['g']}):"]
        lines += [f"- **{CORE[k]['n']}** — {CORE[k]['use']}" for k in group[:6]]
        lines.append("Это уже другое лекарство: заменять — только после консультации с врачом или фармацевтом.")
    if d["note"]:
        lines += ["", f"**Честно о пользе:** {d['note']}"]
    lines += ["", _DOCTOR_NOTE]
    return "\n".join(lines)


