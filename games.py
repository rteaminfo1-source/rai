# ---------------------------------------------------------------- состояние игр
def active(session):
    return bool(session and session.get("game"))


def turn(text, session):
    """Ход в идущей игре. None — сообщение не про игру (игра продолжается)."""
    game = session.get("game") or {}
    low = _low(text)
    kind = game.get("kind")
    if _STOP_RE.match(low):
        session.pop("game", None)
        if kind == "riddle":
            return f"Ответ: **{game['answer']}**. Ещё загадку? Напишите «загадай загадку»."
        if kind == "guess":
            return f"Я загадывал **{game['n']}**. Сыграем ещё — «давай в угадай число»."
        if kind == "quiz":
            return f"Викторина окончена: **{game['score']} из {game['asked']}**. Спасибо за игру!"
        return "Игра окончена. Захотите сыграть — напишите «давай поиграем»."
    if kind == "riddle":
        return _riddle_turn(low, game, session)
    if kind == "guess":
        return _guess_turn(low, game, session)
    if kind == "quiz":
        return _quiz_turn(low, game, session)
    if kind == "cities":
        return _cities_turn(low, game, session)
    session.pop("game", None)
    return None


# ---------------------------------------------------------------- загадки
@tool(CAT, "Загадки", "загадай загадку")
def riddle(text, low, s):
    if not re.search(r"загадай\w*\s+загадк|загадк\w*\s+(?:мне|загадай)|давай\s+загадк|еще\s+загадк|хочу\s+загадк|^загадк\w*\s*\??$", low):
        return None
    used = s.get("riddles_used", [])
    pool = [i for i in range(len(RIDDLES)) if i not in used] or list(range(len(RIDDLES)))
    i = random.choice(pool)
    s["riddles_used"] = (used + [i])[-len(RIDDLES) + 1:]
    q, answers, shown = RIDDLES[i]
    s["game"] = {"kind": "riddle", "answers": answers, "answer": shown, "tries": 0}
    return f"🧩 **Загадка:**\n\n> {q}\n\nНапишите ответ. «Сдаюсь» — покажу отгадку."


_NOT_ANSWER = re.compile(r"^(?:привет|здравствуй\w*|добр\w+ (?:утро|день|вечер)|пока|спасибо|как дела|что ты умеешь|кто ты)\b")


def _riddle_turn(low, game, session):
    if _NOT_ANSWER.match(low) or len(low.split()) > 5:
        return None  # это не ответ — Rai ответит как обычно, загадка подождёт
    if any(a in low for a in game["answers"]):
        session.pop("game", None)
        return f"✅ **Правильно — {game['answer']}!** Ещё загадку?"
    game["tries"] += 1
    if game["tries"] >= 3:
        session.pop("game", None)
        return f"Не угадали. Ответ: **{game['answer']}**. Попробуем ещё одну? Напишите «загадай загадку»."
    return "❌ Нет, не то. Подумайте ещё" + (" — подсказка: первая буква «" + game["answer"][0].upper() + "»." if game["tries"] == 2 else ".")


# ---------------------------------------------------------------- угадай число
@tool(CAT, "Игра «Угадай число»", "давай сыграем в угадай число")
def guess_start(text, low, s):
    if not re.search(r"(?:давай|сыграем|играть|поиграем|игра)\w*\s+(?:в\s+)?(?:\w+\s+)?угада\w*\s+число", low):
        return None
    top = 100
    m = re.search(r"до\s+(\d+)", low)
    if m and 10 <= int(m.group(1)) <= 1_000_000:
        top = int(m.group(1))
    s["game"] = {"kind": "guess", "n": random.randint(1, top), "tries": 0, "top": top}
    return f"🎯 Я загадал число от 1 до {top}. Пишите варианты — я скажу «больше» или «меньше». «Сдаюсь» — открою ответ."


def _guess_turn(low, game, session):
    n = ints(low)
    if not n:
        return None
    g = n[0]
    game["tries"] += 1
    if g == game["n"]:
        session.pop("game", None)
        t = game["tries"]
        return f"🎉 **Угадали: {g}!** Попыток: {t}." + (" Отличный результат!" if t <= 7 else "") + " Ещё раз — «давай в угадай число»."
    return f"{'⬆️ Больше' if g < game['n'] else '⬇️ Меньше'}, чем {g}. Попытка {game['tries']}."


