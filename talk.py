def is_crisis(text):
    return bool(_CRISIS_RE.search(_low(text)))


def support(text):
    """Ответ на «мне грустно», «я устал», «скучно»… или None, если это не про чувства."""
    low = _low(text)
    if is_crisis(low):
        return CRISIS
    if len(low.split()) > 25:
        return None
    for pattern, reply in _MOODS:
        if re.search(pattern, low) and (_ME_RE.search(low) or len(low.split()) <= 3):
            return reply if reply else bored()
    return None
