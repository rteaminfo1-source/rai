def is_recommend_request(text):
    low = _low(text)
    if re.search(r"сделай|создай|напиши код|запрограмм|игру на|игра на", low):
        return False
    if not _REC_RE.search(low):
        return False
    return any(re.search(p, low) for p, _ in _KIND_RE + [(r"заняться", "")]) or any(re.search(p, low) for p, _ in _GENRES)


def recommend(text):
    low = _low(text)
    kind = next((k for p, k in _KIND_RE if re.search(p, low)), "films")
    if re.search(r"чем заняться|скучно", low):
        return bored()
    genre = next((g for p, g in _GENRES if re.search(p, low)), None)
    if kind == "series":
        picks, title = random.sample(SERIES, 5), "Сериалы, которые стоит посмотреть"
        more = "Могу посоветовать и фильмы — напишите «посоветуй комедию» или «фантастику»."
    elif kind == "games":
        picks, title = random.sample(GAMES, 5), "Во что поиграть"
        more = "Для телефона, компьютера или консоли? Уточните — подберу точнее."
    elif kind == "books":
        genre = genre if genre in BOOKS else None
        pool = BOOKS[genre] if genre else [b for v in BOOKS.values() for b in v]
        picks = random.sample(pool, min(5, len(pool)))
        title = f"Книги: {genre}" if genre else "Что почитать"
        more = "Жанры: " + ", ".join(BOOKS) + " — напишите, например, «посоветуй книгу фантастика»."
    else:
        genre = genre if genre in FILMS else None
        pool = FILMS[genre] if genre else [f for v in FILMS.values() for f in v]
        picks = random.sample(sorted(set(pool)), min(5, len(set(pool))))
        title = {"мультфильм": "Мультфильмы", "советский": "Советские фильмы"}.get(genre, f"Фильмы: {genre}" if genre else "Что посмотреть")
        more = "Жанры: " + ", ".join(FILMS) + " — напишите, например, «посоветуй комедию»."
    return f"## {title}\n\n" + "\n".join(f"- {p}" for p in picks) + f"\n\n{more}"


