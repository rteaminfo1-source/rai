@tool(CAT, "Камень, ножницы, бумага", "камень")
def rps(text, low, s):
    m = re.fullmatch(r"\s*(?:я\s+выбираю\s+|играю\s+)?(камень|ножницы|бумага|бумагу)\s*[!.]?\s*", low)
    if not m:
        if re.search(r"камень\W+ножницы\W+бумага", low):
            return "✊✌️✋ Давайте! Напишите «камень», «ножницы» или «бумага»."
        return None
    me = m.group(1).replace("бумагу", "бумага")
    bot = random.choice(["камень", "ножницы", "бумага"])
    wins = {"камень": "ножницы", "ножницы": "бумага", "бумага": "камень"}
    icons = {"камень": "✊", "ножницы": "✌️", "бумага": "✋"}
    res = "Ничья!" if me == bot else ("Вы победили! 🎉" if wins[me] == bot else "Я победил! 😎")
    return f"{icons[me]} против {icons[bot]} — у меня **{bot}**. **{res}**"


