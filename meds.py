def _brands(drug, region):
    """Строки «где как называется»: сначала страна человека, потом остальные."""
    b = drug["b"]
    src = REGIONS.get(region, {}).get("brands", region) if region else None
    lines, used = [], set()
    if region in REGIONS:
        if src in b:
            label = REGIONS[region]["in"]
            if region in ("by", "kz"):
                label += " (те же названия, что в России)"
            if region == "ua":
                label += " (международные названия — российские препараты там не продаются)"
            lines.append(f"- **{label}:** {b[src]}")
            used.add(src)
        else:
            lines.append(f"- **{REGIONS[region]['in']}:** точных названий в моём справочнике нет — спросите в аптеке по действующему веществу")
    for key in ("ru", "us", "uk", "de", "tr", "intl"):
        if key in b and key not in used:
            label = {"ru": "в России и СНГ", "intl": "в других странах (международные названия)"}.get(key, REGIONS[key]["in"])
            lines.append(f"- {label}: {b[key]}")
    return lines


