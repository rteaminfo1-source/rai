@tool(CAT, "Неправильные глаголы английского", "три формы глагола go")
def irregular(text, low, s):
    if not re.search(r"неправильн\w*\s+глагол|форм\w*\s+глагола|irregular|past\s+simple\s+от|вторая\s+форма", low):
        return None
    m = re.search(r"глагол\w*\s+[«\"]?([a-z]+)|(?:форм\w*|от)\s+[«\"]?([a-z]+)", low)
    word = (m.group(1) or m.group(2)) if m else None
    if word:
        for v in IRREGULAR:
            if word in (v[0], v[1], v[2]) or word in v[1].split("/"):
                return f"**{v[0]} — {v[1]} — {v[2]}** ({v[3]})"
        return f"«{word}» — правильный глагол (или его нет в моём списке): {word}ed — {word}ed."
    rows = "\n".join(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in IRREGULAR)
    return f"## Неправильные глаголы ({len(IRREGULAR)})\n\n| Глагол | Past Simple | Past Participle | Перевод |\n|---|---|---|---|\n{rows}"


