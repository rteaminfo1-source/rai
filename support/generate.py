def _expand(s):
    """Все варианты строки шаблона: (а|б) — выбор, [х] — необязательная часть."""
    i = 0
    for i, ch in enumerate(s):
        if ch in "([":
            break
    else:
        return [s]
    close = {"(": ")", "[": "]"}[s[i]]
    depth, j = 0, i
    for j in range(i, len(s)):
        if s[j] in "([":
            depth += 1
        elif s[j] in ")]":
            depth -= 1
            if depth == 0:
                break
    inner, head, tail = s[i + 1:j], s[:i], s[j + 1:]
    parts, depth, cur = [], 0, ""
    for ch in inner:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "|" and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    if close == "]":
        parts = [inner, ""]
    out = []
    for p in parts:
        for e in _expand(p):
            out.extend(head + e + t for t in _expand(tail))
    return out


def expand(template):
    for k, v in COMMON.items():
        template = template.replace("{" + k + "}", v)
    return [re.sub(r"\s+", " ", x).strip() for x in _expand(template)]


def norm(t):
    return re.sub(r"\s+", " ", t.lower().replace("ё", "е")).strip()


def main():
    rng = random.Random(SEED)
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    hand = {norm(e): it["id"] for it in data["intents"] for e in it["examples"]}
    by_intent, owner = {}, {}
    for intent, templates in T.items():
        pool = sorted({x for t in templates for x in expand(t)})
        rng.shuffle(pool)
        # шаблоны каждого вида — поровну, чтобы ни один не забил остальные
        per_t = [sorted(set(expand(t))) for t in templates]
        for lst in per_t:
            rng.shuffle(lst)
        picked, k = [], 0
        while len(picked) < PER_INTENT and any(per_t):
            lst = per_t[k % len(per_t)]
            if lst:
                q = lst.pop()
                if q not in picked:
                    picked.append(q)
            k += 1
        by_intent[intent] = picked
        for q in picked:
            owner.setdefault(norm(q), set()).add(intent)
    # одна фраза — одна тема; ручные примеры главнее
    total = 0
    for intent, qs in by_intent.items():
        keep = [q for q in qs if len(owner[norm(q)]) == 1 and hand.get(norm(q), intent) == intent]
        by_intent[intent] = keep
        total += len(keep)
    ids = [it["id"] for it in data["intents"]]
    missing = [i for i in ids if i not in by_intent]
    out = {"_info": "Сгенерировано support/generate.py из шаблонов — не правьте вручную. Ручные примеры — в data.json.",
           "total": total, "questions": {i: by_intent.get(i, []) for i in ids}}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"Вопросов: {total} (+ {len(hand)} ручных) по {len(ids)} темам → {OUT}")
    for i in ids:
        print(f"  {i:14s} {len(out['questions'][i])}")
    if missing:
        print("Нет шаблонов для:", ", ".join(missing))


if __name__ == "__main__":
    main()
