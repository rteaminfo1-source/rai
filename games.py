    game["used"].append(word)
    letter = _last_letter(word)
    options = [n for n in names if n.lower().replace("ё", "е").startswith(letter) and n.lower().replace("ё", "е") not in game["used"]]
    if not options:
        session.pop("game", None)
        return f"Хм, я не знаю больше городов на «{letter.upper()}». 🏆 Вы победили!"
    pick = random.choice(options)
    game["used"].append(pick.lower().replace("ё", "е"))
    game["need"] = _last_letter(pick)
    note = "" if word in known else " (такого города нет в моём списке, но поверю на слово 🙂)"
    return f"**{pick}**{note}. Вам на **«{game['need'].upper()}»**!"


