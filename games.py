@tool(CAT, "Викторина", "давай викторину")
def quiz_start(text, low, s):
    if not re.search(r"викторин|проверь\s+мои\s+знания|задай\s+(?:мне\s+)?вопрос", low) or re.search(r"сделай|создай|напиши\s+код", low):
        return None
    order = random.sample(range(len(QUIZ)), 5)
    s["game"] = {"kind": "quiz", "order": order, "pos": 0, "score": 0, "asked": 0}
    return "🧠 **Викторина: 5 вопросов.** Отвечайте буквой или словом.\n\n" + _quiz_question(s["game"])


def _quiz_question(game):
    q, opts, _ = QUIZ[game["order"][game["pos"]]]
    return f"**Вопрос {game['pos'] + 1}.** {q}\n\n" + "\n".join(f"{'АБВГ'[i]}) {o}" for i, o in enumerate(opts))


def _quiz_turn(low, game, session):
    q, opts, right = QUIZ[game["order"][game["pos"]]]
    pick = None
    m = re.match(r"^\s*([абвгabcd])\s*[).]?\s*$", low)
    if m:
        pick = "абвгabcd".index(m.group(1)) % 4
    else:
        for i, o in enumerate(opts):
            if o.lower().replace("ё", "е") in low or low in o.lower().replace("ё", "е") and len(low) >= 2:
                pick = i
                break
    if pick is None:
        return "Ответьте буквой (А, Б, В или Г) или словом из вариантов. «Стоп» — закончить."
    game["asked"] += 1
    ok = pick == right
    game["score"] += ok
    head = "✅ Верно!" if ok else f"❌ Неверно. Правильно: **{'АБВГ'[right]}) {opts[right]}**."
    game["pos"] += 1
    if game["pos"] >= len(game["order"]):
        session.pop("game", None)
        sc = game["score"]
        verdict = "Блестяще! 🏆" if sc == 5 else "Отлично!" if sc >= 4 else "Хорошо!" if sc >= 3 else "Есть куда расти — попробуйте ещё раз!"
        return f"{head}\n\n**Итог: {sc} из 5.** {verdict} Ещё раунд — «давай викторину»."
    return f"{head}\n\n" + _quiz_question(game)


# ---------------------------------------------------------------- города
def _city_names():
    names = set()
    for c in getattr(cities, "CITIES", []):
        name = c[0] if isinstance(c, (list, tuple)) else (c.get("name") if isinstance(c, dict) else str(c))
        if name and re.fullmatch(r"[А-ЯЁ][а-яё\- ]+", name):
            names.add(name)
    return sorted(names)


def _last_letter(word):
    w = _low(word)
    for ch in reversed(w):
        if ch not in "ьъыйё -":
            return ch
    return w[-1]


