def _norm(s):
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е")).strip(" .,!?-")


def _stem_key(s):
    return " ".join(nlp.stem(w) for w in re.split(r"[\s-]+", _norm(s)) if w)


def _forms(name):
    """Падежные формы названия: «Минск» → минске, минска, минску; «Москва» → москве, москвы, москву."""
    parts = re.split(r"([\s-]+)", _norm(name))
    first = parts[0]
    out = {first}
    if re.search(r"[бвгджзклмнпрстфхцчшщ]$", first):
        out |= {first + "е", first + "а", first + "у", first + "ом"}
    elif first.endswith("а"):
        out |= {first[:-1] + e for e in ("е", "ы", "и", "у", "ой")}
    elif first.endswith("я"):
        out |= {first[:-1] + e for e in ("е", "и", "ю")}
    elif first.endswith("ь"):
        out |= {first[:-1] + "и", first[:-1] + "ью"}
    elif first.endswith("й"):
        out |= {first[:-1] + e for e in ("е", "я", "ю")}
    return {f + "".join(parts[1:]) for f in out}


_INDEX = None


def _index():
    global _INDEX
    if _INDEX is None:
        _INDEX = {}
        for name in CITIES:
            for key in _forms(name) | {_norm(name), _stem_key(name)}:
                _INDEX.setdefault(key, name)
        for alias, name in ALIASES.items():
            _INDEX[_norm(alias)] = name
    return _INDEX


def find(phrase):
    """Город из справочника: {"name", "latitude", "longitude", "country"} или None."""
    idx = _index()
    p = _norm(phrase)
    for key in (p, _stem_key(phrase)):
        if key in idx:
            name = idx[key]
            lat, lon, country = CITIES[name]
            return {"name": name, "latitude": lat, "longitude": lon, "country": country}
    return None
