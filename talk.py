_POEM_RE = re.compile(r"стих|стишок|стишк|стихотворени|четверостиши|поэм\w|рифм\w* про|в стихах|поздравлени\w* стих", re.I)
_COMPOSE_RE = re.compile(r"придума|сочин|напиши|написать|сделай|создай|составь|нужен|нужно|хочу", re.I)
_AUTHORS = {"пушкин": "Пушкин", "тютчев": "Тютчев", "есенин": "Есенин", "лермонтов": "Лермонтов",
            "фет": "Фет", "плещеев": "Плещеев"}


def is_poem_request(text):
    low = _low(text)
    return bool(_POEM_RE.search(low)) and not re.search(r"что такое стих|размер стиха|ямб|хорей|как писать стих", low)


def poem(text):
    """Стихотворение по теме или автору. Своё («придумай») — в первую очередь, классика — если просят автора."""
    low = _low(text)
    author = next((name for key, name in _AUTHORS.items() if key in low), None)
    m = re.search(r"\b(?:про|о|об|на тему|для|к)\s+(.+)", low)
    topic = (m.group(1) if m else low).strip(" ?!.")
    pool = [p for p in POEMS if author and author in p[2]] if author else [p for p in POEMS if re.search(p[0], topic)]
    if not author and pool and _COMPOSE_RE.search(low):
        own = [p for p in pool if p[2] == "Rai"]
        pool = own or pool
    if not pool:
        if author:
            return f"Стихов автора «{author}» у меня в памяти нет. Спросите «стих Пушкина», «стих Есенина» — или подключите внешнюю нейросеть в меню модели внизу."
        if m:
            themes = "осень, зима, весна, лето, мама, папа, друг, любовь, кот, собака, море, школа, учитель, день рождения, Новый год, программист"
            return (f"Про «{topic}» готового стихотворения у меня нет. Новое сочинит "
                    f"внешняя нейросеть Rai Нейро — её можно подключить в меню модели внизу.\n\nСвои стихи у меня есть на темы: {themes}.")
        pool = [p for p in POEMS if p[2] == "Rai"]
    _, title, by, body = random.choice(pool)
    note = "*Сочинил Rai для вас.*" if by == "Rai" else f"*{by}*"
    return f"### {title}\n\n{body}\n\n{note}"


