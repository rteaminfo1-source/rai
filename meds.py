# какие названия к какому препарату (для поиска во всех падежах)
_SHORT_OK = {"ацц"}   # короткие, но однозначные названия
_INDEX = []
for _k, _d0 in CORE.items():
    names = {_d0["n"].lower(), _d0["n"].split("(")[0].strip().lower()} | {a.lower() for a in _d0["al"]}
    inn0 = _d0["inn"].split("(")[0].strip().lower()
    if len(inn0) >= 6:
        names.add(inn0)
    for reg in _d0["b"].values():
        for part in re.split(r",|\(|\)|—", reg):
            part = part.strip()
            # торговые названия пишутся с большой буквы; пояснения в скобках («детский», «по рецепту») — нет
            if part and (part[0].isupper() or part[0].isdigit()) and 3 < len(part) < 40 and not part.startswith("В составе"):
                names.add(part.lower())
    for nm in names:
        if (len(nm) >= 4 or nm in _SHORT_OK) and nm != "—":
            _INDEX.append((nm.replace("ё", "е"), _k))
_INDEX.sort(key=lambda x: -len(x[0]))
_ENDS = r"(?:а|у|ом|е|ы|и|ой|ов|ам|ами|ах|ем|ю|ей)?"
_ENDS_A = r"(?:а|ы|е|у|ой|ою|и|я|ю|ей)"


def _norm(text):
    return re.sub(r"\s+", " ", (text or "").lower().replace("ё", "е")).strip()


def find(text):
    """Препараты из встроенного справочника, которые упомянуты в тексте (в любой форме слова): [ключ, …]."""
    low = _norm(text)
    found = []
    for n, key in _INDEX:
        if key in found:
            continue
        # название целиком; русские — в любом падеже («нурофена», «парацетамолом», «смекты»), но не «кандидат» от «Кандид»
        if re.search("[а-я]$", n) and len(n) >= 5:
            body = re.escape(n[:-1]) + _ENDS_A if n[-1] in "ая" else re.escape(n) + _ENDS
        else:
            body = re.escape(n)
        if re.search(r"(?<![a-zа-я0-9])" + body + r"(?![a-zа-я0-9])", low):
            found.append(key)
    return found


