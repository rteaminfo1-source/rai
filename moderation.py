def _variants(text):
    low = (text or "").lower().replace("ё", "е")
    mapped = low.translate(_LOOKALIKE)
    squeezed = re.sub(r"(\w)\1+", r"\1", mapped)                    # «хууууй» → «хуй»
    joined = re.sub(r"\b(\w)(?:[\s._-](\w))+\b", lambda m: m.group(0).replace(" ", "").replace(".", "").replace("_", "").replace("-", ""), mapped)
    return [low, mapped, squeezed, joined]                           # «х у й» — тоже


def _mask(word):
    word = word.strip()
    return word[:1] + "*" * max(1, len(word) - 2) + word[-1:] if len(word) > 2 else word[:1] + "*"


def check(text):
    """Нарушение правил: {"category", "label", "word" (замаскировано), "answer"} или None."""
    if not text or not text.strip():
        return None
    for variant in _variants(text[:4000]):
        for cat, patterns in _COMPILED:
            for rx in patterns:
                m = rx.search(variant)
                if m:
                    found = {"category": cat, "label": LABELS[cat], "word": _mask(m.group(0)) if cat == "мат" else m.group(0)[:60]}
                    found["answer"] = reply(found)
                    return found
    return None


def reply(found):
    return (f"⛔ **Диалог остановлен.** Сообщение нарушает [правила Rai]({RULES_URL}): {found['label']}.\n\n"
            "Я не продолжаю этот разговор. Начните **новый чат** — и, пожалуйста, без этого. "
            "Администрация получила уведомление; за повторные нарушения аккаунт блокируется.")
