_DB = {"items": [], "index": {}}
_SUFFIX = re.compile(r"(?:ами|ями|ого|его|ому|ему|ыми|ими|ом|ем|ам|ям|ах|ях|ов|ев|ей|ой|ую|юю|ая|яя|ое|ее|ые|ие|ий|ый|а|я|у|ю|ы|и|е|о)$")


def _stem(phrase):
    """«ацетилсалициловую кислоту» и «ацетилсалициловая кислота» → одна и та же основа."""
    return " ".join(_SUFFIX.sub("", w) if len(w) > 4 else w for w in re.findall(r"[a-zа-я0-9-]+", _norm(phrase)))


def load(data):
    """Большая база препаратов (из medicines.json): {"items": [{"n", "en", "al", "d", "atc", "for", "cls", "brands", "rx", "x"}]}."""
    items = (data or {}).get("items") or []
    index = {}
    for i, it in enumerate(items):
        for nm in [it.get("n"), it.get("en")] + list(it.get("al") or []) + list(it.get("brands") or []):
            key = _stem(nm or "")
            if len(key) >= 4:
                index.setdefault(key, i)
    _DB["items"], _DB["index"] = items, index
    return len(items)


def db_find(text):
    """Препарат из большой базы (если его нет во встроенном справочнике): запись или None."""
    if not _DB["items"]:
        return None
    words = _stem(text).split()
    for size in (4, 3, 2, 1):
        for i in range(len(words) - size + 1):
            key = " ".join(words[i:i + size])
            if len(key) >= 4 and key in _DB["index"]:
                return _DB["items"][_DB["index"][key]]
    return None


