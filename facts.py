def _norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[«»\"'.,!?()]", " ", (s or "").lower().replace("ё", "е"))).strip()


def _stem(w):
    return w[:-1] if len(w) > 3 and w[-1] in "аеиоуыэюяйь" else w


def _key_re(k):
    """Ключ с любыми окончаниями слов: «мона лиза» находит и «мону лизу»."""
    return r"(?<![а-яa-z])" + r"\s+".join(re.escape(_stem(w)) + r"[а-яa-z]*" for w in k.split())


def _find(table, low):
    """Самый длинный ключ из таблицы, который есть в вопросе."""
    best = None
    for keys, value in table:
        for k in keys:
            if re.search(_key_re(k), low) and (best is None or len(k) > best[0]):
                best = (len(k), value)
    return best[1] if best else None


