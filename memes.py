_INDEX = None


def _norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", (s or "").lower().replace("ё", "е"))).strip()


def _index():
    global _INDEX
    if _INDEX is None:
        _INDEX = []
        for title, keys, what, how in MEMES:
            for k in keys:
                # «~» — слово многозначное («сигма», «бумер»): считаем мемом, только если спросили именно про мем
                _INDEX.append((_norm(k.lstrip("~")), title, what, how, k.startswith("~")))
        _INDEX.sort(key=lambda x: -len(x[0]))  # длинные ключи раньше: «сигма бой» раньше «сигма»
    return _INDEX


MEME_RE = re.compile(r"(?<![а-яё])мем\w*|meme", re.I)
_ASK_RE = re.compile(r"(?<![а-яё])(что (такое|значит|за|означает)|кто так\w*|откуда|расскажи|объясни|что за мем|знаешь)", re.I)
_RANDOM_RE = re.compile(r"(?<![а-яё])(расскажи|покажи|скинь|кинь|дай|давай|какой.*популяр|смешн|случайн|любой|рандомн).*мем|"
                        r"^мем\w*[\s?!.]*$|топ\w* мем|популярн\w* мем|мемы? (20\d\d|года|сейчас)", re.I)


def find(text, about_meme=False):
    """Мем из базы по тексту: (название, что это, как используют) или None."""
    t = " " + _norm(text) + " "
    for key, title, what, how, needs_word in _index():
        if needs_word and not about_meme:
            continue
        if len(key) <= 3:
            if re.search(r"(?<!\w)" + re.escape(key) + r"(?!\w)", t):
                return title, what, how
        elif " " + key in t or key in t and len(key) >= 6:
            return title, what, how
    return None


def is_meme_request(text):
    """Вопрос про мем: «что за мем ждун», «откуда мем Шлёпа», «кто такой гигачад», «расскажи мем»."""
    if MEME_RE.search(text or ""):
        return True
    return bool(_ASK_RE.search(text or "") and find(text))


_LIST_RE = re.compile(r"(топ\w*|популярн\w*|главн\w*|модн\w*|новы\w*|свеж\w*|последн\w*|какие|список|все).{0,20}мем|мемы? (20\d\d|года|сейчас)", re.I)


def _first(text):
    return re.split(r"(?<=[.!?])\s", text)[0]


def answer(text):
    """Ответ про мем или None (тогда Rai ищет в интернете)."""
    about = bool(MEME_RE.search(text or ""))
    rest = re.sub(r"мем\w*", " ", text or "", flags=re.I)
    hit = find(rest, about)
    if not hit and _LIST_RE.search(text or ""):
        year = re.search(r"20\d\d", text)
        pool = [m for m in MEMES if year and year.group() in m[2]] or random.sample(MEMES, 10)
        lines = ["- **" + m[0] + "** — " + _first(m[2]) for m in pool[:10]]
        head = f"## Мемы {year.group()} года" if year and pool[0][2].find(year.group()) >= 0 else "## Популярные мемы"
        return head + "\n\n" + "\n".join(lines) + "\n\nСпросите про любой: «что за мем …» — расскажу подробнее."
    if not hit and _RANDOM_RE.search(text or ""):
        title, keys, what, how = random.choice(MEMES)
        top = ", ".join(m[0] for m in random.sample(MEMES, 6) if m[0] != title)
        return f"**{title}** — {what}\n\n**Как используют:** {how}\n\nЕщё спросите про: {top}."
    if not hit:
        return None
    title, what, how = hit
    return f"**{title}** — {what}\n\n**Как используют:** {how}"


def topic(text):
    """Название мема из вопроса (для поиска в интернете): «что за мем бобр курва» → «бобр курва мем»."""
    t = re.sub(r"(?<![а-яё])(что (такое|значит|за|означает)|откуда|расскажи( про| о)?|объясни|кто так\w*|знаешь( ли)?( ты)?|"
               r"мем\w*|про|пожалуйста|[?!.,«»\"])", " ", text or "", flags=re.I)
    t = re.sub(r"\s+", " ", t).strip()
    return (t + " мем").strip() if t else ""
