@tool(CAT, "Химические элементы", "химический символ золота")
def element(text, low, s):
    if not re.search(r"элемент|химическ|символ|атомн|менделеев|обозначает\w*\s+[a-z]", low) and not re.search(r"\b(?:что такое|какой элемент)\s+[A-Z][a-z]?\b", text):
        return None
    hit = None
    for z, sym, name, mass in ELEMENTS:
        stem = name.lower()[:-1] if len(name) > 4 else name.lower()
        if re.search(r"(?<![а-я])" + stem, low) or re.search(r"(?<![A-Za-z])" + sym + r"(?![a-z])", text) and re.search(r"символ|элемент|обозначает|что такое|какой", low):
            hit = (z, sym, name, mass)
            if re.search(r"(?<![а-я])" + stem, low):
                break
    m = re.search(r"(?:элемент\w*|номер)\s+(?:под\s+)?(?:номером\s+)?(\d{1,3})\b", low)
    if m and not hit:
        hit = next((e for e in ELEMENTS if e[0] == int(m.group(1))), None)
    if not hit:
        return None
    z, sym, name, mass = hit
    return f"**{name} — {sym}**, порядковый номер {z}, атомная масса {mass}."


