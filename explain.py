_COMPILED = [(tuple(re.compile(p) for p in need + ((cue,) if cue else ())), text) for cue, need, text in EXPLAIN]


def _norm(text):
    return re.sub(r"\s+", " ", (text or "").lower().replace("ё", "е")).strip()


def answer(text):
    """Объяснение на вопрос «почему / как / зачем …» или None. Самое точное из подходящих."""
    t = _norm(text)
    if not t or len(t) > 200 or not _ASK_RE.search(t):
        return None
    best, score = None, 0
    for need, reply in _COMPILED:
        if all(p.search(t) for p in need):
            s = len(need) * 1000 + sum(len(p.pattern) for p in need)
            if s > score:
                best, score = reply, s
    return best


